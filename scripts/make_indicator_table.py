"""Regenerate pdf417_tool/indicator_table.py from zxing-cpp's PDF417 encoder.

Row indicator codewords depend only on a symbol's rows, columns, and error
level, so encoding every legal size and reading those codewords back from the
1-pixel-per-module bitmap yields the bar pattern of every value they can take.
"""

from __future__ import annotations

from itertools import groupby
from pathlib import Path

import zxingcpp
from PIL import Image

OUTPUT = Path(__file__).resolve().parent.parent / "pdf417_tool" / "indicator_table.py"


def widths(bits: str) -> str:
    return "".join(str(len(list(run))) for _bit, run in groupby(bits))


def main() -> None:
    tables: list[dict[str, int]] = [{}, {}, {}]
    for rows in range(3, 91):
        for columns in range(1, 31):
            if rows * columns > 928:
                continue
            for level in range(9):
                if (2 << level) + 2 > rows * columns:
                    continue
                barcode = zxingcpp.create_barcode(
                    "1", zxingcpp.BarcodeFormat.PDF417, columns=columns, rows=rows, ec_level=str(level)
                )
                image = Image.fromarray(barcode.to_image(scale=1, add_quiet_zones=False)).convert("L")
                width, height = image.size
                pixels = image.load()
                lines = [
                    "".join("1" if pixels[x, y] < 128 else "0" for x in range(width)) for y in range(height)
                ]
                lines = [line for line, _same in groupby(lines)]
                if width != 17 * columns + 69 or len(lines) != rows:
                    raise SystemExit(f"unexpected symbol for {rows}x{columns} level {level}")
                for row, line in enumerate(lines):
                    base = 30 * (row // 3)
                    rows_part, level_part, columns_part = (rows - 1) // 3, level * 3 + (rows - 1) % 3, columns - 1
                    left, right = (
                        (rows_part, columns_part),
                        (level_part, rows_part),
                        (columns_part, level_part),
                    )[row % 3]
                    for bits, value in ((line[17:34], base + left), (line[width - 35 : width - 18], base + right)):
                        known = tables[row % 3].setdefault(widths(bits), value)
                        if known != value:
                            raise SystemExit(f"pattern conflict in cluster {row % 3}")

    lines = [
        '"""Bar/space widths of PDF417 row indicator codewords. Generated by scripts/make_indicator_table.py."""',
        "",
        "# One table per cluster (row number modulo 3), mapping the eight element",
        "# widths in modules, bar first, to the codeword value.",
        "INDICATOR_PATTERNS: tuple[dict[str, int], ...] = (",
    ]
    for table in tables:
        lines.append("    {")
        items = sorted(table.items(), key=lambda item: item[1])
        for start in range(0, len(items), 6):
            chunk = ", ".join(f'"{key}": {value}' for key, value in items[start : start + 6])
            lines.append(f"        {chunk},")
        lines.append("    },")
    lines.append(")")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT} ({sum(len(table) for table in tables)} patterns)")


if __name__ == "__main__":
    main()
